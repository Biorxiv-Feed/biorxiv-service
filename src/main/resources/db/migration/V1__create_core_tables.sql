CREATE TABLE users
(
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    telegram_id         BIGINT       NOT NULL,
    username            VARCHAR(255),
    daily_article_limit INTEGER      NOT NULL DEFAULT 10,
    active              BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at          TIMESTAMP    NOT NULL,
    CONSTRAINT uk_users_telegram_id UNIQUE (telegram_id),
    CONSTRAINT ck_users_daily_article_limit CHECK (daily_article_limit >= 0)
);

CREATE TABLE articles
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doi              VARCHAR(255) NOT NULL,
    version          INTEGER      NOT NULL,
    title            TEXT         NOT NULL,
    authors          TEXT,
    abstract         TEXT,
    category         VARCHAR(255),
    publication_date DATE,
    jatsxml          TEXT,
    created_at       TIMESTAMP    NOT NULL,
    CONSTRAINT uk_articles_doi_version UNIQUE (doi, version)
);

CREATE INDEX idx_articles_category ON articles (category);
CREATE INDEX idx_articles_publication_date ON articles (publication_date);

CREATE TABLE subscriptions
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL,
    category   VARCHAR(255) NOT NULL,
    created_at TIMESTAMP    NOT NULL,
    CONSTRAINT fk_subscriptions_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT uk_subscriptions_user_category UNIQUE (user_id, category)
);

-- subscriptions.user_id is covered by uk_subscriptions_user_category (user_id is its leading column).
-- Finding subscribers of a given category needs its own index.
CREATE INDEX idx_subscriptions_category ON subscriptions (category);

CREATE TABLE notifications
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL,
    article_id BIGINT      NOT NULL,
    status     VARCHAR(50) NOT NULL,
    attempts   INTEGER     NOT NULL DEFAULT 0,
    last_error TEXT,
    sent_at    TIMESTAMP,
    created_at TIMESTAMP   NOT NULL,
    CONSTRAINT fk_notifications_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_notifications_article FOREIGN KEY (article_id) REFERENCES articles (id),
    CONSTRAINT uk_notifications_user_article UNIQUE (user_id, article_id),
    CONSTRAINT ck_notifications_attempts CHECK (attempts >= 0)
);

-- notifications.user_id is covered by uk_notifications_user_article (user_id is its leading column).
CREATE INDEX idx_notifications_article_id ON notifications (article_id);
CREATE INDEX idx_notifications_status ON notifications (status);